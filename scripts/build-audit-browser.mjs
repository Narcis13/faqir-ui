#!/usr/bin/env node
/**
 * Build the browser bundle of the audit engine (task 0.7-14, FAQIR-PLAN §13).
 *
 *   src/audit/browser.ts  ──bun build──▶  site/lib/faqir-audit.js
 *
 * The output is a single IIFE that installs `window.FaqirAudit` and loads with a
 * plain `<script src>` — no module graph, no import map, works off `file://`.
 * It is what lets the docs-site playground audit markup with **no server**: the
 * same `auditHtmlSource` the CLI runs, shipped to the page.
 *
 * The bundle is COMMITTED (like `registry/core/faqir-core.js`) because
 * `src/generator/docs.ts` is pure and `node:fs`-only — it copies the bundle into
 * the site rather than invoking a bundler — so `bun test`, the Playwright runner
 * and `bun run build:docs` all see the same bytes without a build ordering rule.
 * `--check` is the drift gate that keeps the committed bytes honest.
 *
 * Usage:
 *   bun run build:audit-browser            → write site/lib/faqir-audit.js
 *   bun run build:audit-browser -- --check → exit 1 if the committed bundle is stale
 *
 * Runnable via either `bun run …` or `node scripts/build-audit-browser.mjs`
 * (it shells out to `bun build`, exactly as `scripts/build-cli.mjs` does).
 */
import { spawnSync } from "node:child_process";
import { gzipSync } from "node:zlib";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = join(ROOT, "src", "audit", "browser.ts");
const OUTFILE = join(ROOT, "site", "lib", "faqir-audit.js");

const HEADER = `/* Faqir audit engine — browser bundle.
 * GENERATED by scripts/build-audit-browser.mjs from src/audit/browser.ts.
 * Do not edit by hand; run \`bun run build:audit-browser\`.
 * Installs one global: FaqirAudit. Zero dependencies, no network, no DOM needed.
 */
`;

const checkOnly = process.argv.slice(2).includes("--check");

/** Bundle the entry to a string. Throws with a readable message if Bun is absent. */
function bundle() {
  const scratch = mkdtempSync(join(tmpdir(), "faqir-audit-bundle-"));
  const target = join(scratch, "faqir-audit.js");
  try {
    const bun = process.env.FAQIR_BUN || "bun";
    const result = spawnSync(
      bun,
      [
        "build",
        ENTRY,
        "--target=browser",
        "--format=iife",
        "--minify",
        `--outfile=${target}`,
      ],
      { cwd: ROOT, encoding: "utf8" },
    );
    if (result.error) {
      if (result.error.code === "ENOENT") {
        throw new Error(
          "build:audit-browser requires Bun to compile the bundle. Install Bun from https://bun.sh and retry.",
        );
      }
      throw new Error(`failed to launch ${bun}: ${result.error.message}`);
    }
    if (result.status !== 0) {
      throw new Error(`bun build exited ${result.status}:\n${result.stderr ?? ""}`);
    }
    return HEADER + readFileSync(target, "utf8").replace(/^\/\/#[^\n]*\n?/gm, "").trimEnd() + "\n";
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

let output;
try {
  output = bundle();
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
}

const kb = (bytes) => `${(bytes / 1024).toFixed(2)} KB`;
const raw = Buffer.byteLength(output);
const gzip = gzipSync(output).length;

if (checkOnly) {
  const current = existsSync(OUTFILE) ? readFileSync(OUTFILE, "utf8") : null;
  if (current !== output) {
    process.stderr.write(
      current === null
        ? `site/lib/faqir-audit.js is missing — run \`bun run build:audit-browser\`.\n`
        : `site/lib/faqir-audit.js is stale — run \`bun run build:audit-browser\`.\n`,
    );
    process.exit(1);
  }
  process.stdout.write(`✓ site/lib/faqir-audit.js up to date — ${kb(raw)} raw · ${kb(gzip)} gzip\n`);
  process.exit(0);
}

mkdirSync(dirname(OUTFILE), { recursive: true });
writeFileSync(OUTFILE, output);
process.stdout.write(`✓ site/lib/faqir-audit.js — ${kb(raw)} raw · ${kb(gzip)} gzip\n`);
