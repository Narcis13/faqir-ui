#!/usr/bin/env bun
/**
 * Pin the v0.2.4 registry's honoured surface (task 1.0-03, FAQIR-PLAN §15).
 *
 * `tests/fixtures/v024/surface.json` is the "before" side of the migration
 * gate: for every component the last 0.x release shipped, every attribute value
 * its manifest declared or its stylesheet and controller selected on. The test
 * suite compares it against today's registry and fails when a component has
 * quietly stopped honouring something a v0.2.4 page could legally carry.
 *
 * The source is the release tag itself — `git archive v0.2.4 registry` — read
 * through `extractSurface`, the same function the test runs against the current
 * registry. The output is content-only and sorted, so a rerun that changes
 * nothing rewrites the same bytes.
 *
 * Run: `bun scripts/gen-v024-surface.mjs` (or `--check` to verify the committed
 * file is current). Regeneration is only ever needed if the extractor changes;
 * the tag it reads cannot move.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractRegistrySurface, MIGRATION_FROM_VERSION } from "../src/migration.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "tests", "fixtures", "v024", "surface.json");
const TAG = `v${MIGRATION_FROM_VERSION}`;

const checkOnly = process.argv.includes("--check");

const work = mkdtempSync(join(tmpdir(), "faqir-v024-"));
try {
  const archive = join(work, "registry.tar");
  execFileSync("git", ["archive", "--output", archive, TAG, "registry"], { cwd: ROOT });
  mkdirSync(join(work, "tree"), { recursive: true });
  execFileSync("tar", ["-xf", archive, "-C", join(work, "tree")]);

  const surface = extractRegistrySurface(join(work, "tree", "registry"));
  const document = {
    _comment: `The honoured component surface of the ${TAG} release, generated by scripts/gen-v024-surface.mjs. Do not hand-edit.`,
    release: MIGRATION_FROM_VERSION,
    components: surface,
  };
  const serialized = JSON.stringify(document, null, 2) + "\n";

  if (checkOnly) {
    const current = readFileSync(OUT, "utf8");
    if (current !== serialized) {
      console.error(`${OUT} is stale — run 'bun scripts/gen-v024-surface.mjs'.`);
      process.exit(1);
    }
    console.log(`✓ v${MIGRATION_FROM_VERSION} surface is current (${Object.keys(surface).length} components).`);
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, serialized);
    console.log(`✓ Wrote ${OUT} (${Object.keys(surface).length} components).`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
