#!/usr/bin/env bun
/**
 * Pin the v1.0.0 registry's honoured surface (task 1.1R-01).
 *
 * `tests/fixtures/v100/surface.json` is the "before" side of the 1.1 migration
 * gate, produced exactly as `gen-v024-surface.mjs` produces the 0.x one: every
 * component the 1.0.0 release shipped, and every attribute value its manifest
 * declared or its stylesheet and controller selected on. 1.1 promises no
 * breaking change, and `tests/migration/surface-v100.test.ts` holds it to that —
 * today's registry must honour every one of these values.
 *
 * The source is the release tag itself — `git archive v1.0.0 registry` — read
 * through `extractRegistrySurface`, the same function the test runs against the
 * current registry. Content-only and sorted, so a rerun rewrites the same bytes.
 *
 * Run: `bun scripts/gen-v100-surface.mjs` (or `--check` to verify the committed
 * file is current). Regeneration is only ever needed if the extractor changes;
 * the tag it reads cannot move.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractRegistrySurface } from "../src/migration.ts";
import { BUILD_TIMEOUT_MS } from "./spawn.mjs";

const RELEASE = "1.0.0";
const TAG = `v${RELEASE}`;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "tests", "fixtures", "v100", "surface.json");

const checkOnly = process.argv.includes("--check");

const work = mkdtempSync(join(tmpdir(), "faqir-v100-"));
try {
  const archive = join(work, "registry.tar");
  execFileSync("git", ["archive", "--output", archive, TAG, "registry"], {
    cwd: ROOT,
    timeout: BUILD_TIMEOUT_MS,
    killSignal: "SIGKILL",
  });
  mkdirSync(join(work, "tree"), { recursive: true });
  execFileSync("tar", ["-xf", archive, "-C", join(work, "tree")], {
    timeout: BUILD_TIMEOUT_MS,
    killSignal: "SIGKILL",
  });

  const surface = extractRegistrySurface(join(work, "tree", "registry"));
  const document = {
    _comment: `The honoured component surface of the ${TAG} release, generated by scripts/gen-v100-surface.mjs. Do not hand-edit.`,
    release: RELEASE,
    components: surface,
  };
  const serialized = JSON.stringify(document, null, 2) + "\n";

  if (checkOnly) {
    const current = readFileSync(OUT, "utf8");
    if (current !== serialized) {
      console.error(`${OUT} is stale — run 'bun scripts/gen-v100-surface.mjs'.`);
      process.exit(1);
    }
    console.log(`✓ ${TAG} surface is current (${Object.keys(surface).length} components).`);
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, serialized);
    console.log(`✓ Wrote ${OUT} (${Object.keys(surface).length} components).`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
