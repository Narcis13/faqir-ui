#!/usr/bin/env node
/**
 * Build the browser plugin from `@faqir-ui/rules` (task 1.1B-04, FAQIR-PLAN-1.1 §8.3).
 *
 *   packages/rules/src/plugin.js  ──bun build──▶  registry/core/plugins/faqir-rules.js
 *
 * The output is a single self-registering IIFE that loads with a plain
 * `<script src>` after faqir-core and faqir-validate. It carries the evaluator
 * with it, which is the entire point: the verdict a page reaches and the
 * verdict a server reaches come from the same compiled bytes, so "browser and
 * server agree" is a property of the build rather than a promise two
 * implementations make to each other.
 *
 * The bundle is COMMITTED, like `registry/core/faqir-core.js` and
 * `site/lib/faqir-audit.js`: `faqir add` copies registry files with `node:fs`
 * and never invokes a bundler, so the plugin has to exist on disk. `--check` is
 * the drift gate that keeps the committed bytes honest — it is byte-for-byte,
 * so it is pinned to the `BUN_VERSION` in `.github/workflows/ci.yml` exactly as
 * `check:core-package` and `check:audit-browser` are.
 *
 * The header is not written here: it is the `@ui:` lines and the doc comment at
 * the top of the source, lifted verbatim, because `src/generator/plugins.ts`
 * reads that header to document the plugin in the generated skill. A plugin
 * that documents itself in one place documents itself everywhere.
 *
 * Usage:
 *   bun run build:rules-plugin            → write registry/core/plugins/faqir-rules.js
 *   bun run build:rules-plugin -- --check → exit 1 if the committed bundle is stale
 *
 * Runnable via either `bun run …` or `node scripts/build-rules-plugin.mjs`.
 */
import { gzipSync } from "node:zlib";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BUILD_TIMEOUT_MS, isTimeout, spawnBudgeted, timeoutMessage } from "./spawn.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = join(ROOT, "packages", "rules", "src", "plugin.js");
const OUTFILE = join(ROOT, "registry", "core", "plugins", "faqir-rules.js");

const NOTICE = [
  "// GENERATED by scripts/build-rules-plugin.mjs from packages/rules/src/plugin.js",
  "// and the @faqir-ui/rules evaluator it imports. Do not edit by hand; run",
  "// `bun run build:rules-plugin`.",
].join("\n");

/**
 * The source's own header: its `// @ui:` lines, then its doc comment.
 *
 * Both halves are contracts. `src/generator/plugins.ts` requires `@ui:plugin` /
 * `@ui:provides` on their own lines at the top, and reads the doc comment's
 * summary, indented example and following paragraph into
 * `references/directives.md`. The GENERATED notice goes BETWEEN them, as `//`
 * lines, because that generator takes the first `* …` line it finds as the
 * plugin's description — a `/* … *\/` banner above the doc comment would
 * silently become the description.
 */
function header(source) {
  const match = /^((?:\/\/[^\n]*\n)+)(\/\*\*[\s\S]*?\*\/\n)/.exec(source);
  if (!match) {
    throw new Error(
      "packages/rules/src/plugin.js must start with its `// @ui:` lines followed by a " +
        "/** … */ header comment — that header is what documents the plugin in the skill.",
    );
  }
  for (const line of ["// @ui:plugin faqir-rules", "// @ui:provides l-rules"]) {
    if (!match[1].includes(`${line}\n`)) {
      throw new Error(`packages/rules/src/plugin.js is missing its \`${line}\` line.`);
    }
  }
  return `${match[1]}${NOTICE}\n${match[2]}`;
}

/** Bundle the entry to a string. Throws with a readable message if Bun is absent. */
function bundle() {
  const scratch = mkdtempSync(join(tmpdir(), "faqir-rules-plugin-"));
  const target = join(scratch, "faqir-rules.js");
  try {
    const bun = process.env.FAQIR_BUN || "bun";
    const args = [
      "build",
      ENTRY,
      "--target=browser",
      "--format=iife",
      "--minify",
      `--outfile=${target}`,
    ];
    const result = spawnBudgeted(bun, args, {
      cwd: ROOT,
      encoding: "utf8",
      timeout: BUILD_TIMEOUT_MS,
    });
    if (isTimeout(result)) {
      throw new Error(`build:rules-plugin ${timeoutMessage(bun, args)}`);
    }
    if (result.error) {
      if (result.error.code === "ENOENT") {
        throw new Error(
          "build:rules-plugin requires Bun to compile the bundle. Install Bun from https://bun.sh and retry.",
        );
      }
      throw new Error(`failed to launch ${bun}: ${result.error.message}`);
    }
    if (result.status !== 0) {
      throw new Error(`bun build exited ${result.status}:\n${result.stderr ?? ""}`);
    }
    const code = readFileSync(target, "utf8").replace(/^\/\/#[^\n]*\n?/gm, "").trimEnd();
    return `${header(readFileSync(ENTRY, "utf8"))}${code}\n`;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

const checkOnly = process.argv.slice(2).includes("--check");

let output;
try {
  output = bundle();
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
}

const kb = (bytes) => `${(bytes / 1024).toFixed(2)} KB`;
const raw = Buffer.byteLength(output);
const gzip = gzipSync(output).length;

if (checkOnly) {
  const current = existsSync(OUTFILE) ? readFileSync(OUTFILE, "utf8") : null;
  if (current !== output) {
    process.stderr.write(
      current === null
        ? "registry/core/plugins/faqir-rules.js is missing — run `bun run build:rules-plugin`.\n"
        : "registry/core/plugins/faqir-rules.js is stale — run `bun run build:rules-plugin`.\n",
    );
    process.exit(1);
  }
  process.stdout.write(
    `✓ registry/core/plugins/faqir-rules.js up to date — ${kb(raw)} raw · ${kb(gzip)} gzip\n`,
  );
  process.exit(0);
}

mkdirSync(dirname(OUTFILE), { recursive: true });
writeFileSync(OUTFILE, output);
process.stdout.write(`✓ registry/core/plugins/faqir-rules.js — ${kb(raw)} raw · ${kb(gzip)} gzip\n`);
