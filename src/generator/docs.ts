/**
 * The site stylesheet: tokens, base, theme, then every component stylesheet —
 * the same cascade order `faqir init` installs. One file, one `<link>`, so a
 * page works from any directory depth and any static host.
 */
export function buildSiteStylesheet(registryRoot: string, theme: string): string {
  const parts: string[] = [`/* ${DOCS_GENERATION_MARKER} — do not edit by hand */`];

  parts.push("/* ── tokens ── */");
  for (const name of TOKEN_FILES) {
    const path = join(registryRoot, "tokens", `${name}.css`);
    if (!existsSync(path)) continue;
    parts.push(
      readText(path)
        .split("\n")
        .filter((line) => !line.startsWith("@import"))
        .join("\n"),
    );
  }

  parts.push("/* ── base ── */");
  for (const name of BASE_FILES) {
    const path = join(registryRoot, "base", `${name}.css`);
    if (existsSync(path)) parts.push(readText(path));
  }

  const themePath = join(registryRoot, "themes", `${theme}.css`);
  if (existsSync(themePath)) {
    parts.push(`/* ── theme: ${theme} ── */`);
    parts.push(readText(themePath));
  }

  parts.push("/* ── components ── */");
  for (const layer of LAYERS) {
    const base = join(registryRoot, layer);
    if (!existsSync(base)) continue;
    for (const file of walkCss(base)) parts.push(readText(file));
  }

  return parts.join("\n") + "\n";
}

