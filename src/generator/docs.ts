interface ShellInput {
  /** Site-relative path of the page being rendered (drives every relative URL). */
  pagePath: string;
  title: string;
  description: string;
  /** Main-content HTML, already escaped/assembled. */
  body: string;
  config: SiteConfig;
  components: DocsComponent[];
  /** Nav entry that should carry `aria-current="page"`. */
  current: string;
}

/**
 * The navigation shell every site page shares: the `dashboard-shell` pattern,
 * with the sidebar listing every component grouped by layer. It is generated
 * from the same component list the pages are, so a new component appears in the
 * nav of all 80-odd pages without a site edit.
 *
 * The sidebar deliberately carries **no** `data-state`. Below dashboard-shell's
 * 768px breakpoint the pattern turns it into an off-canvas drawer that only
 * `data-state="expanded"` slides in, so pinning it open would park the whole
 * component list on top of the content on a phone. Left at its default it is a
 * column on desktop and steps aside on mobile, where the header nav and the
 * component index carry navigation (the site ships no JavaScript of its own, so
 * there is no drawer toggle to offer).
 */
function renderShell(input: ShellInput): string {
  const { pagePath, config, components, current } = input;
  const u = (to: string) => escAttr(relUrl(pagePath, to));
  const currentAttr = (key: string) => (key === current ? ' aria-current="page"' : "");

  const groups = LAYERS.map((layer) => ({
    layer,
    items: components.filter((c) => c.layer === layer),
  })).filter((g) => g.items.length > 0);

  const navGroups = groups
    .map(
      (g) =>
        `        <h2 data-ui="text" data-size="xs" data-variant="subtle" data-weight="semibold">${esc(
          LAYER_LABEL[g.layer],
        )}</h2>\n` +
        g.items
          .map(
            (c) =>
              `        <a data-part="nav-item" href="${u(c.pagePath)}"${currentAttr(
                c.pagePath,
              )}>${esc(c.name)}</a>`,
          )
          .join("\n"),
    )
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en" data-theme="auto">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escAttr(input.title)}</title>
<meta name="description" content="${escAttr(input.description)}">
<link rel="stylesheet" href="${u("styles/faqir.css")}">
<!-- ${DOCS_GENERATION_MARKER} · regenerate with \`bun run build:docs\` · do not edit by hand -->
</head>
<body>
<div data-ui="dashboard-shell">

  <aside data-part="sidebar">
    <a data-part="logo" href="${u("index.html")}"><span>${esc(config.title)}</span></a>
    <hr data-ui="separator">
    <nav data-part="nav" role="navigation" aria-label="Documentation">
      <a data-part="nav-item" href="${u("index.html")}"${currentAttr("index.html")}>Overview</a>
      <a data-part="nav-item" href="${u("components/index.html")}"${currentAttr(
        "components/index.html",
      )}>All components</a>
      <a data-part="nav-item" href="${u("tokens/index.html")}"${currentAttr(
        "tokens/index.html",
      )}>Design tokens</a>
      <hr data-ui="separator">
${navGroups}
    </nav>
  </aside>

  <header data-part="header" role="banner">
    <a data-ui="link" href="${u("index.html")}"><strong>${esc(config.title)}</strong></a>
    <nav data-ui="nav" aria-label="Site sections">
      <a data-part="link" href="${u("components/index.html")}">Components</a>
      <a data-part="link" href="${u("tokens/index.html")}">Tokens</a>
    </nav>
  </header>

  <main data-part="content" role="main">
    <article data-ui="prose" style="max-width: 72rem;">
${input.body}
    </article>
  </main>

  <footer data-part="footer">
    <span>${esc(config.footer)}</span>
  </footer>

</div>
</body>
</html>
`;
}

